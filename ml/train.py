"""Reproducible research models. All examples and targets are synthetic, not field data."""
import json, pathlib, csv
import numpy as np
import torch
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score, f1_score

ROOT = pathlib.Path(__file__).resolve().parents[1]
torch.set_num_threads(2)
torch.manual_seed(42)
rng = np.random.default_rng(42)
FEATURES = ['severity', 'population', 'damage', 'access', 'capacity', 'communication', 'demand', 'vulnerability']
N, K = 1400, 12
x = rng.uniform(0, 1, (N,K,8)).astype('float32')
adj = np.zeros((N,K,K), dtype='float32')
for s in range(N):
    for i in range(K):
        adj[s,i,(i+1)%K] = adj[s,(i+1)%K,i] = 1
    for i in range(K):
        for j in range(i+2,K):
            if rng.random() < .16:
                adj[s,i,j] = adj[s,j,i] = 1
adj += np.eye(K, dtype='float32')[None]
adj /= adj.sum(-1, keepdims=True)
neighbor = adj @ x
# A transparent simulated generating process, NOT physical hazard ground truth.
local = .35*x[:,:,0]+.13*x[:,:,1]+.15*x[:,:,2]+.12*(1-x[:,:,3])+.07*(1-x[:,:,4])+.05*(1-x[:,:,5])+.08*x[:,:,6]+.05*x[:,:,7]
y = np.clip(.79*local + .21*(adj @ local[...,None]).squeeze(-1) + rng.normal(0,.012,(N,K)),0,1).astype('float32')
train, valid, test = slice(0,1000), slice(1000,1200), slice(1200,1400)

class RiskGCN(torch.nn.Module):
    def __init__(self):
        super().__init__()
        self.local = torch.nn.Linear(8,24)
        self.neighbor = torch.nn.Linear(8,24, bias=False)
        self.out = torch.nn.Linear(24,1)
    def forward(self,x,a):
        return torch.sigmoid(self.out(torch.relu(self.local(x)+self.neighbor(a@x)))).squeeze(-1)

model = RiskGCN()
optim = torch.optim.Adam(model.parameters(), lr=.018)
tx,ta,ty = map(torch.tensor, (x,adj,y))
best = float('inf'); weights = None
for epoch in range(400):
    model.train(); optim.zero_grad()
    loss = ((model(tx[train],ta[train])-ty[train])**2).mean()
    loss.backward(); optim.step()
    with torch.no_grad():
        v = ((model(tx[valid],ta[valid])-ty[valid])**2).mean().item()
        if v < best:
            best=v; weights={k:v.clone() for k,v in model.state_dict().items()}
model.load_state_dict(weights); model.eval()
rf = RandomForestRegressor(n_estimators=32,max_depth=8,min_samples_leaf=5,random_state=42,n_jobs=2)
rf.fit(x[train].reshape(-1,8),y[train].reshape(-1))
with torch.no_grad(): gp=model(tx[test],ta[test]).numpy().reshape(-1)
rp=rf.predict(x[test].reshape(-1,8)); actual=y[test].reshape(-1)
def metrics(pred):
    cls=lambda a: np.digitize(a,[.4,.6,.75])
    return {'mae':round(float(mean_absolute_error(actual,pred)*100),3),'rmse':round(float(np.sqrt(mean_squared_error(actual,pred))*100),3),'r2':round(float(r2_score(actual,pred)),4),'macro_f1':round(float(f1_score(cls(actual),cls(pred),average='macro')),4)}
trees=[]
for estimator in rf.estimators_:
    t=estimator.tree_
    trees.append({'left':t.children_left.tolist(),'right':t.children_right.tolist(),'feature':t.feature.tolist(),'threshold':t.threshold.tolist(),'value':t.value[:,0,0].tolist()})
artifact={'version':'1.0.0','seed':42,'provenance':'synthetic-only','features':FEATURES,'architecture':'GraphSAGE-style mean-aggregation graph neural network, 8 → 24 → 1, sigmoid; plus random forest baseline',
 'splits':{'train_graphs':1000,'validation_graphs':200,'test_graphs':200,'nodes_per_graph':12},
 'metrics':{'gnn':metrics(gp),'forest':metrics(rp),'ensemble':metrics(.7*gp+.3*rp)},
 'weights':{k:v.detach().numpy().tolist() for k,v in model.state_dict().items()},'trees':trees,
 'limitations':['Targets are generated by a stated synthetic rule. Test metrics measure approximation of that rule only.','No real-world validation or calibrated uncertainty.','Not the SSF-GNN satellite-image model or Evolve-DGN reinforcement-learning method cited by the paper.']}
(ROOT/'lib').mkdir(exist_ok=True)
(ROOT/'lib'/'models.json').write_text(json.dumps(artifact,separators=(',',':')))
(ROOT/'ml'/'evaluation.json').write_text(json.dumps({k:v for k,v in artifact.items() if k not in ['weights','trees']},indent=2))
fixture={'regions':[{'id':f'R{i}','name':f'Test {i}','hazard':'Flood','people':1000,**dict(zip(FEATURES,map(float,x[1200,i])))} for i in range(K)], 'roads':[{'from':f'R{i}','to':f'R{j}','open':True,'minutes':10} for i in range(K) for j in range(i+1,K) if adj[1200,i,j]>0], 'expected_gnn':[int(np.floor(v*100+.5)) for v in gp[:K]], 'expected_forest':[int(np.floor(v*100+.5)) for v in rp[:K]]}
(ROOT/'ml'/'inference-fixture.json').write_text(json.dumps(fixture))
with (ROOT/'ml'/'synthetic-sample.csv').open('w',newline='') as f:
    writer=csv.writer(f);writer.writerow(['scenario','region',*FEATURES,'target'])
    for s in range(10):
        for i in range(K): writer.writerow([s,i,*x[s,i].tolist(),float(y[s,i])])
print(json.dumps(artifact['metrics'],indent=2))
